// Generates supabase/seed.sql from the bundled content in src/data, so the CMS starts with
// exactly what the live site shows today.   Run:  npm run cms:seed
// The SQL only inserts rows that do not exist yet (ON CONFLICT DO NOTHING / skip if FAQs exist),
// so running it again never overwrites edits made in the CMS.
import { writeFileSync } from 'node:fs';
import { products, gridOrder } from '../src/data/products.mjs';
import { faq, content } from '../src/data/site.mjs';

const TAG = '$cms$';
const lit = (v) => { const s = typeof v === 'string' ? v : JSON.stringify(v); if (s.includes(TAG)) throw new Error(`content contains ${TAG}`); return `${TAG}${s}${TAG}`; };

const order = [...gridOrder, ...products.map(p => p.letter).filter(l => !gridOrder.includes(l))];
const sortOf = (p) => (order.indexOf(p.letter) + 1) * 10;

const sql = `-- Generated by scripts/cms-seed.mjs from src/data — do not edit by hand.
-- Loads today's catalogue, FAQs and section copy into the CMS. Run once after schema.sql.
-- Re-running is safe: existing rows are left untouched.

begin;

insert into public.products (slug, sort_order, published, data) values
${products.map(p => `  (${lit(p.slug)}, ${sortOf(p)}, true, ${lit(p)}::jsonb)`).join(',\n')}
on conflict (slug) do nothing;

insert into public.faqs (question, answer, sort_order, published)
select v.question, v.answer, v.sort_order, true
from (values
${faq.map(([q, a], i) => `  (${lit(q)}, ${lit(a)}, ${(i + 1) * 10})`).join(',\n')}
) as v (question, answer, sort_order)
where not exists (select 1 from public.faqs);

insert into public.site_content (key, value) values
${Object.entries(content).map(([k, v]) => `  (${lit(k)}, ${lit(v)}::jsonb)`).join(',\n')}
on conflict (key) do nothing;

commit;
`;

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql);
console.log(`supabase/seed.sql: ${products.length} products, ${faq.length} FAQs, ${Object.keys(content).length} content keys`);
